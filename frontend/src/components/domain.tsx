export function LiveDot({ color = "var(--color-ok)", className }: { color?: string; className?: string }) {
  return (
    <span className={cn("relative inline-flex size-2", className)}>
      <span className="absolute inset-0 rounded-full animate-pulse-ring" style={{ background: color }} />
      <span className="relative inline-flex size-2 rounded-full" style={{ background: color }} />
    </span>
  );
}

export function AnimatedNumber({ value, className, suffix = "", style }: { value: number; className?: string; suffix?: string; style?: React.CSSProperties }) {
  const mv = useMotionValue(value);
  const rounded = useTransform(mv, (v) => Math.round(v).toLocaleString());
  const [text, setText] = useState(Math.round(value).toLocaleString());
  useEffect(() => rounded.on("change", setText), [rounded]);
  useEffect(() => {
    const c = animate(mv, value, { duration: 0.8, ease: [0.2, 0.7, 0.2, 1] });
    return () => c.stop();
  }, [value, mv]);
  return <span className={cn("tnum", className)} style={style}>{text}{suffix}</span>;
}

export function RiskRing({ value, size = 120, stroke = 9, night, label = "Risk", color }: {
  value: number; size?: number; stroke?: number; night?: boolean; label?: string; color?: string;
}) {
  const r = (size - stroke) / 2;
  const c = 2 * Math.PI * r;
  const col = color ?? (value >= 85 ? "var(--color-critical)" : value >= 65 ? "var(--color-high)" : value >= 45 ? "var(--color-medium)" : "var(--color-ok)");
  return (
    <div className="relative" style={{ width: size, height: size }}>
      <svg width={size} height={size} className="-rotate-90">
        <circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke={night ? "rgba(255,255,255,0.08)" : "var(--color-subtle)"} strokeWidth={stroke} />
        <motion.circle cx={size / 2} cy={size / 2} r={r} fill="none" stroke={col} strokeWidth={stroke} strokeLinecap="round"
          strokeDasharray={c} initial={{ strokeDashoffset: c }} animate={{ strokeDashoffset: c * (1 - Math.min(100, value) / 100) }}
          transition={{ type: "spring", stiffness: 60, damping: 18 }} />
      </svg>
      <div className="absolute inset-0 flex flex-col items-center justify-center">
        <AnimatedNumber value={value} style={{ fontSize: Math.round(size * 0.27), lineHeight: 1 }}
          className={cn("font-semibold tracking-[-0.04em]", night ? "text-white" : "text-ink")} />
        <span className={cn("text-[10.5px] font-medium uppercase tracking-[0.08em]", night ? "text-white/45" : "text-muted")}>{label}</span>
      </div>
    </div>
  );
}

export function Metric({ label, value, hint, icon, tone, suffix }: {
  label: string; value: number | string; hint?: ReactNode; icon?: ReactNode; tone?: "critical" | "ok" | "accent"; suffix?: string;
}) {
  return (
    <div className="card flex flex-col justify-between gap-5 p-5">
      <div className="flex items-center justify-between">
        <span className="text-[12.5px] font-medium text-muted">{label}</span>
        {icon && <span className={cn("flex size-7 items-center justify-center rounded-lg bg-white/[0.05] text-ink-2 ring-1 ring-line [&_svg]:size-3.5",
          tone === "critical" && "bg-critical-soft text-critical", tone === "ok" && "bg-ok-soft text-ok", tone === "accent" && "bg-accent-soft text-accent")}>{icon}</span>}
      </div>
      <div>
        <div className="text-[30px] font-semibold leading-none tracking-[-0.04em]">
          {typeof value === "number" ? <AnimatedNumber value={value} suffix={suffix} /> : value}
        </div>
        {hint && <div className="mt-2 text-[12px] text-muted">{hint}</div>}
      </div>
    </div>
  );
}

export function PageHeader({ eyebrow, title, description, actions, highlight }: { eyebrow: ReactNode; title: string; description?: ReactNode; actions?: ReactNode; highlight?: string }) {
  return (
    <div className="mb-8 flex flex-col gap-5 md:flex-row md:items-end md:justify-between">
      <div className="max-w-2xl">
        <div className="eyebrow mb-3"><TrackIn>{eyebrow}</TrackIn></div>
        <RiseWords text={title} highlight={highlight} className="display text-[36px] leading-[1.04] md:text-[46px]" />
        {description && (
          <motion.p initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.8, delay: 0.35, ease: [0.16, 1, 0.3, 1] }}
            className="mt-4 text-[15px] leading-relaxed text-muted">{description}</motion.p>
        )}
      </div>
      {actions && (
        <motion.div initial={{ opacity: 0, y: 8 }} animate={{ opacity: 1, y: 0 }} transition={{ duration: 0.7, delay: 0.45 }}
          className="flex shrink-0 flex-wrap items-center gap-2">{actions}</motion.div>
      )}
    </div>
  );
}

export function ErrorState({ error, onRetry }: { error: string; onRetry?: () => void }) {
  return (
    <div className="card flex flex-col items-center gap-3 px-6 py-12 text-center">
      <div className="flex size-10 items-center justify-center rounded-full bg-critical-soft text-critical"><AlertTriangle className="size-5" /></div>
      <div className="text-[15px] font-semibold">Gateway unreachable</div>
      <p className="max-w-md text-[13px] text-muted">{error}</p>
      {onRetry && <button onClick={onRetry} className="text-[13px] font-medium text-accent hover:underline">Try again</button>}
    </div>
  );
}

