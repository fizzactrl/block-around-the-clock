import { AlertTriangle, CheckCircle2, CircleDashed, FlaskConical, Loader2, ShieldAlert, XCircle } from "lucide-react";
import { animate, motion, useMotionValue, useTransform } from "motion/react";
import type React from "react";
import { useEffect, useState, type ReactNode } from "react";
import { Badge } from "@/components/ui/badge";
import { RiseWords, TrackIn } from "@/components/motion";
import { Tip } from "@/components/ui/tooltip";
import type { ActionStatus, IncidentStatus, Severity } from "@/lib/types";
import { cn } from "@/lib/utils";

export const SEVERITY_COLOR: Record<Severity, string> = {
  critical: "var(--color-critical)", high: "var(--color-high)", medium: "var(--color-medium)", low: "var(--color-ok)",
};

export function SeverityBadge({ severity, night }: { severity: Severity; night?: boolean }) {
  const tone = night ? (severity === "critical" || severity === "high" ? "nightCritical" : "night") : severity === "low" ? "ok" : severity;
  return (
    <Badge tone={tone}>
      <span className="size-1.5 rounded-full" style={{ background: SEVERITY_COLOR[severity] }} />
      {severity[0].toUpperCase() + severity.slice(1)}
    </Badge>
  );
}

const STATUS_META: Record<IncidentStatus, { label: string; tone: "accent" | "high" | "ok" | "critical" | "neutral" }> = {
  DETECTED: { label: "Detected", tone: "high" },
  ANALYZED: { label: "Analyzed", tone: "accent" },
  CONTAINING: { label: "Containing", tone: "accent" },
  CONTAINED: { label: "Contained", tone: "ok" },
  ATTENTION_REQUIRED: { label: "Attention required", tone: "critical" },
};

export function StatusBadge({ status }: { status: IncidentStatus }) {
  const m = STATUS_META[status];
  return (
    <Badge tone={m.tone}>
      {status === "CONTAINING" ? <Loader2 className="animate-spin" /> : status === "CONTAINED" ? <CheckCircle2 /> :
        status === "ATTENTION_REQUIRED" ? <AlertTriangle /> : <ShieldAlert />}
      {m.label}
    </Badge>
  );
}

export function ActionStatusIcon({ status, className }: { status: ActionStatus; className?: string }) {
  if (status === "SUCCEEDED") return <CheckCircle2 className={cn("size-[18px] text-ok", className)} />;
  if (status === "FAILED") return <XCircle className={cn("size-[18px] text-critical", className)} />;
  if (status === "EXECUTING") return <Loader2 className={cn("size-[18px] animate-spin text-accent", className)} />;
  return <CircleDashed className={cn("size-[18px] text-faint", className)} />;
}

