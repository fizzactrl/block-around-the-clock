DISCLAIMER = ("Generated by the Block Around the Clock hackathon demo. Containment actions "
              "were executed by SIMULATED adapters and did not reach any real carrier, bank, identity provider or "
              "credit bureau. Nothing in this document has been filed with the FTC, law enforcement or any regulator, "
              "and it does not constitute legal advice or a statement of regulatory compliance.")

PII_CATEGORY_NAMES = {"PHONE": "Phone numbers", "SSN": "Social Security numbers", "PERSON": "Personal names",
                      "BANK": "Financial institution names", "ACCOUNT": "Account numbers", "OTP": "One-time codes / PINs",
                      "EMAIL": "Email addresses", "CARD": "Payment card numbers"}


def _fmt_args(args: dict) -> str:
    return ", ".join(f"{k}={v}" for k, v in args.items() if k != "rationale")


def agent_trace(incident_id: str) -> dict | None:
    run = agent.latest_for(incident_id)
    if not run:
        return None
    lines = []
    for s in run["steps"]:
        k = s["kind"]
        if k == "model_turn":
            lines.append({"n": s["n"], "ts": s["ts"], "kind": "decision", "label": f"Nemotron turn {s['turn']}",
                          "detail": f"{s['latency_ms']} ms · {s.get('tokens') or 0} tokens → {', '.join(s['tool_calls']) or 'no tool call'}"})
        elif k == "assessment":
            a = s["args"]
            lines.append({"n": s["n"], "ts": s["ts"], "kind": "assessment", "label": f"Assessment · {a.get('severity')}",
                          "detail": f"{a.get('threat_summary')} Objectives: {'; '.join(a.get('objectives', []))}"})
        elif k == "tool_call":
            lines.append({"n": s["n"], "ts": s["ts"], "kind": "replan" if s.get("replan") else "tool_call",
                          "label": f"{'Replan → ' if s.get('replan') else ''}{s['tool']}({_fmt_args(s['args'])})",
                          "detail": s["args"].get("rationale", "")})
        elif k == "observation":
            res = s["result"]
            lines.append({"n": s["n"], "ts": s["ts"], "kind": "observation" if res.get("ok") else "failure",
                          "label": f"{'OK' if res.get('ok') else 'FAILED'} · {res.get('code')}", "detail": res.get("message", "")})
        elif k in ("final", "escalation"):
            a = s["args"]
            lines.append({"n": s["n"], "ts": s["ts"], "kind": k, "label": s["tool"],
                          "detail": a.get("summary") or f"{a.get('reason')} — {a.get('blocking_issue')}"})
    return {"run_id": run["id"], "model": run["model"], "served_model": run.get("served_model"), "status": run["status"],
            "turns": run["turns"], "tokens": run["usage"]["total_tokens"], "model_latency_ms": run["model_latency_ms"],
            "environment": run.get("environment", []), "outcome": run.get("outcome"), "error": run.get("error"),
            "engine": run.get("engine"), "steps": lines}


def build(incident_id: str, mark_generated=True) -> dict:
    status = orchestrator.advance(incident_id)
    inc, actions = status["incident"], status["actions"]
    logs = audit.for_incident(incident_id)
    chain = audit.verify()
    analysis = inc.get("analysis") or {}
    decision = analysis.get("decision") or {}
    exposed = inc["privacy"]["entities_removed"]
    now = clock.now()
    if mark_generated:
        orchestrator._set(incident_id, report_generated_at=now)

    timeline = [{"ts": l["ts"], "event": l["event_type"], "summary": l["summary"], "actor": l["actor"],
                 "classification": "simulated" if l["event_type"].startswith("containment.") else "system-observed",
                 "hash": l["hash"][:16]} for l in logs]
    evidence = [{"ref": f"EVD-{i + 1:02d}", "kind": "audit-entry", "pointer": f"audit_logs.seq={l['seq']}",
                 "sha256": l["hash"]} for i, l in enumerate(logs[:1])]
    evidence += [{"ref": f"EVD-{len(evidence) + i + 1:02d}", "kind": "sanitized-event", "pointer": ref,
                  "sha256": hashlib.sha256(ref.encode()).hexdigest()} for i, ref in enumerate(inc.get("evidence_refs", []))]
    transcript_digest = hashlib.sha256(json.dumps(inc.get("sanitized_transcript", []), sort_keys=True).encode()).hexdigest()
    evidence.append({"ref": f"EVD-{len(evidence) + 1:02d}", "kind": "sanitized-transcript",
                     "pointer": f"incidents/{incident_id}.sanitized_transcript", "sha256": transcript_digest})

    trace = agent_trace(incident_id)
    succeeded = [a for a in actions if a["status"] == "SUCCEEDED"]
    failed = [a for a in actions if a["status"] == "FAILED"]
    return {
        "report_id": f"RPT-{incident_id[4:]}", "incident_id": incident_id, "generated_at": now,
        "status": "DRAFT — REQUIRES HUMAN REVIEW", "disclaimer": DISCLAIMER,
        "identification": {
            "incident_id": incident_id, "title": inc["title"], "threat_type": inc["threat_type"],
            "severity": inc["severity"], "risk_score": inc["risk_score"], "status": inc["status"],
            "source": inc["source"], "detected_at": inc["created_at"], "contained_at": inc.get("contained_at"),
            "data_classification": "Synthetic demo data" if inc.get("simulated") else "Production",
        },
        "summary": ((trace or {}).get("outcome") or {}).get("summary") or (inc.get("agent_assessment") or {}).get("threat_summary")
                   or decision.get("summary") or "AI analysis not yet run.",
        "agent_trace": trace,
        "ai_commander": {"engine": "nemotron-agent" if trace else analysis.get("engine"),
                         "model": (trace or {}).get("model") or analysis.get("model"),
                         "confidence": decision.get("confidence"),
                         "missing_information": decision.get("missing_information", []),
                         "policy": analysis.get("policy")},
        "facts": {
            "confirmed": [f"Risk engine scored the interaction {inc['risk_score']}/99 ({inc['severity']}).",
                          *[f"Indicator observed: {s['label']}." for s in inc.get("signals", [])],
                          f"{inc['privacy']['total_removed']} sensitive value(s) were tokenized before AI processing.",
                          f"Audit chain verification: {'intact' if chain['valid'] else 'BROKEN'} "
                          f"({chain['entries']} entries)."],
            "simulated": ["Caller audio, carrier signalling and telemetry were generated by the carrier simulator.",
                          *[f"Simulated environment condition: {c}." for c in adapters.describe_env(inc.get("sim_env"))],
                          *[f"{a['label']} — {a['status'].lower()} via simulated adapter "
                            f"(ref {(a.get('result') or {}).get('reference') or 'n/a'})." for a in actions]],
            "unverified": decision.get("missing_information", []) or
                          ((trace or {}).get("outcome") or {}).get("residual_risks", []),
        },
        "timeline": timeline,
        "evidence": evidence,
        "containment": {"total": len(actions), "succeeded": len(succeeded), "failed": len(failed),
                        "actions": [{"label": a["label"], "status": a["status"], "attempts": a["attempts"],
                                     "requested_by": a["requested_by"], "completed_at": a.get("completed_at"),
                                     "reference": (a.get("result") or {}).get("reference"),
                                     "message": (a.get("result") or {}).get("message"), "simulated": True}
                                    for a in actions]},
        "audit_chain": chain,
        "ftc_draft": {
            "title": "Draft identity theft report — for the consumer to review and submit themselves",
            "note": "Mirrors the information typically requested by IdentityTheft.gov. Not submitted.",
            "fields": [
                {"label": "What happened", "value": decision.get("summary", ""), "source": "system"},
                {"label": "How the thief contacted you", "value": f"Phone call ({inc['threat_type']})", "source": "system"},
                {"label": "Information the caller requested",
                 "value": ", ".join(PII_CATEGORY_NAMES.get(k, k) for k in exposed) or "None detected", "source": "system"},
                {"label": "Your name and contact details", "value": "[TO BE COMPLETED BY CONSUMER]", "source": "consumer"},
                {"label": "Accounts affected", "value": "[TO BE COMPLETED BY CONSUMER — tokenized in this system]",
                 "source": "consumer"},
                {"label": "Steps already taken", "value": "; ".join(a["label"] for a in succeeded) +
                 " (simulated in this demo — verify with each provider)", "source": "system"},
                {"label": "Police report number", "value": "[OPTIONAL — TO BE COMPLETED]", "source": "consumer"},
            ],
        },
        "regulatory_scope": {
            "note": "Preliminary scoping aid for counsel. Not a determination of any notification obligation.",
            "data_categories_involved": [{"category": PII_CATEGORY_NAMES.get(k, k), "occurrences": n}
                                         for k, n in exposed.items()],
            "considerations": [
                "Assess whether any data element was actually disclosed by the subscriber (see missing information).",
                "SSN or account-number exposure may implicate state breach-notification statutes — counsel to review.",
                "Telecom carriers may have CPNI-related obligations if customer network information was accessed.",
                "Retain sanitized audit chain and evidence hashes per your legal-hold policy.",
            ],
            "human_review_required": True,
        },
    }


def pdf(incident_id: str) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import LETTER
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    r = build(incident_id)
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=LETTER, leftMargin=0.8 * inch, rightMargin=0.8 * inch,
                            topMargin=0.75 * inch, bottomMargin=0.75 * inch,
                            title=f"Incident report {incident_id}", author="Block Around the Clock (demo)")
    ss = getSampleStyleSheet()
    ink, muted, line = colors.HexColor("#0B0B0F"), colors.HexColor("#6B6B76"), colors.HexColor("#E6E6EA")
    h1 = ParagraphStyle("h1", parent=ss["Title"], fontName="Helvetica-Bold", fontSize=20, leading=24,
                        textColor=ink, alignment=0, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold", fontSize=12, textColor=ink,
                        spaceBefore=14, spaceAfter=6)
    body = ParagraphStyle("b", parent=ss["BodyText"], fontName="Helvetica", fontSize=9, leading=13, textColor=ink)
    small = ParagraphStyle("s", parent=body, fontSize=7.5, leading=10, textColor=muted)
    warn = ParagraphStyle("w", parent=body, textColor=colors.HexColor("#8A2B0E"), backColor=colors.HexColor("#FFF4EE"),
                          borderPadding=8, borderColor=colors.HexColor("#F5C8B4"), borderWidth=0.6)

    def esc(s):
        return str(s if s is not None else "—").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    def table(rows, widths, header=True):
        t = Table([[Paragraph(esc(c), small if (header and i == 0) else body) for c in row] for i, row in enumerate(rows)],
                  colWidths=widths, repeatRows=1 if header else 0)
        t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 0.4, line), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("TOPPADDING", (0, 0), (-1, -1), 4), ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
        return t

    ident = r["identification"]
    story = [Paragraph("Block Around the Clock · Incident report", small),
             Paragraph(f"{esc(ident['title'])}", h1),
             Paragraph(f"{esc(r['report_id'])} · {esc(ident['incident_id'])} · generated {esc(r['generated_at'])}", small),
             Spacer(1, 10), Paragraph(f"<b>{esc(r['status'])}.</b> {esc(r['disclaimer'])}", warn),
             Paragraph("1. Incident identification", h2),
             table([[k.replace("_", " ").title(), v] for k, v in ident.items()], [1.8 * inch, 5 * inch], header=False),
             Paragraph("2. Summary", h2), Paragraph(esc(r["summary"]), body),
             Paragraph(f"AI commander: {esc(r['ai_commander']['engine'])} · model {esc(r['ai_commander']['model'])} · "
                       f"confidence {esc(r['ai_commander']['confidence'])}", small),
             Paragraph("3. Facts — confirmed vs simulated", h2)]
    for label, key in (("System-observed", "confirmed"), ("Simulated", "simulated"), ("Unverified / missing", "unverified")):
        story.append(Paragraph(f"<b>{label}</b>", body))
        for item in r["facts"][key] or ["None"]:
            story.append(Paragraph(f"• {esc(item)}", body))
        story.append(Spacer(1, 4))
    story += [Paragraph("4. Containment actions (simulated adapters)", h2),
              table([["Action", "Status", "Attempts", "Reference"]] +
                    [[a["label"], a["status"], a["attempts"], a["reference"] or "—"] for a in r["containment"]["actions"]],
                    [2.6 * inch, 1.2 * inch, 0.8 * inch, 2.2 * inch]),
              *([Paragraph("Agent action trace (NVIDIA Nemotron)", h2),
                 Paragraph(f"Run {esc(r['agent_trace']['run_id'])} · model {esc(r['agent_trace']['model'])} · "
                           f"status {esc(r['agent_trace']['status'])} · {r['agent_trace']['turns']} model turns · "
                           f"{r['agent_trace']['tokens']} tokens", small),
                 table([["#", "Step", "Detail"]] + [[t["n"], t["label"], t["detail"]] for t in r["agent_trace"]["steps"]],
                       [0.4 * inch, 2.6 * inch, 3.8 * inch])] if r.get("agent_trace") else []),
              Paragraph("5. Timeline of events", h2),
              table([["Time (UTC)", "Event", "Class", "Hash"]] +
                    [[t["ts"][11:19], t["summary"], t["classification"], t["hash"]] for t in r["timeline"]],
                    [0.9 * inch, 3.7 * inch, 1.0 * inch, 1.2 * inch]),
              Paragraph("6. Evidence references", h2),
              table([["Ref", "Kind", "Pointer", "SHA-256"]] +
                    [[e["ref"], e["kind"], e["pointer"], e["sha256"][:24] + "…"] for e in r["evidence"]],
                    [0.7 * inch, 1.3 * inch, 2.6 * inch, 2.2 * inch]),
              Paragraph(f"Audit chain: {'intact' if r['audit_chain']['valid'] else 'BROKEN'} · "
                        f"{r['audit_chain']['entries']} entries · head {r['audit_chain']['head'][:24]}… "
                        "(hash chaining provides tamper evidence, not immutable storage)", small),
              Paragraph("7. Draft FTC identity theft documentation", h2),
              Paragraph(esc(r["ftc_draft"]["note"]), small),
              table([["Field", "Draft value", "Source"]] + [[f["label"], f["value"], f["source"]]
                                                           for f in r["ftc_draft"]["fields"]],
                    [1.8 * inch, 4.0 * inch, 1.0 * inch]),
              Paragraph("8. Regulatory incident scope (for counsel)", h2),
              Paragraph(esc(r["regulatory_scope"]["note"]), small)]
    for c in r["regulatory_scope"]["data_categories_involved"]:
        story.append(Paragraph(f"• {esc(c['category'])}: {c['occurrences']} occurrence(s) — tokenized", body))
    for c in r["regulatory_scope"]["considerations"]:
        story.append(Paragraph(f"• {esc(c)}", body))
    story += [Spacer(1, 18), Paragraph("Reviewed by: ____________________   Date: ____________   "
                                       "Approved for submission: ☐ Yes ☐ No", body)]

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(muted)
        canvas.drawString(0.8 * inch, 0.45 * inch, f"DRAFT — requires human review · {incident_id} · simulated demo data")
        canvas.drawRightString(LETTER[0] - 0.8 * inch, 0.45 * inch, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()
